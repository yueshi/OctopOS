-- Schema v43: app-owned inbound ingress. Mirrors SQLite.

CREATE TABLE IF NOT EXISTS light_app_ingress (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ingress_id      TEXT NOT NULL UNIQUE,
  app_id          TEXT NOT NULL REFERENCES light_apps(app_id) ON DELETE CASCADE,
  name            TEXT NOT NULL,
  mode            TEXT NOT NULL,
  source_id       TEXT NOT NULL REFERENCES external_sources(source_id) ON DELETE CASCADE,
  subscription_id TEXT NOT NULL REFERENCES external_subscriptions(subscription_id)
                  ON DELETE CASCADE,
  enabled         INTEGER NOT NULL DEFAULT 1,
  created_by      INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at      INTEGER NOT NULL,
  updated_at      INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_light_app_ingress_app
  ON light_app_ingress(app_id);

UPDATE _schema_version SET version = 43;
