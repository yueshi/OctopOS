-- Schema v52: MiniApp external write services.
-- One declaration can now describe an HTTP extension (provider=extension)
-- with read/write tool contracts. The operations table is a thin idempotency
-- ledger for invoke; it is not a task runtime.

ALTER TABLE light_app_services ADD COLUMN IF NOT EXISTS mode TEXT NOT NULL DEFAULT 'read';
ALTER TABLE light_app_services ADD COLUMN IF NOT EXISTS base_url TEXT NOT NULL DEFAULT '';
ALTER TABLE light_app_services ADD COLUMN IF NOT EXISTS extension_id TEXT NOT NULL DEFAULT '';
ALTER TABLE light_app_services ADD COLUMN IF NOT EXISTS secret_ref TEXT NOT NULL DEFAULT '';
ALTER TABLE light_app_services
  ADD COLUMN IF NOT EXISTS read_tools_json TEXT NOT NULL DEFAULT '[]';
ALTER TABLE light_app_services
  ADD COLUMN IF NOT EXISTS write_tools_json TEXT NOT NULL DEFAULT '[]';
ALTER TABLE light_app_services
  ADD COLUMN IF NOT EXISTS timeout_seconds INTEGER NOT NULL DEFAULT 30;
ALTER TABLE light_app_services
  ADD COLUMN IF NOT EXISTS max_request_bytes INTEGER NOT NULL DEFAULT 65536;
ALTER TABLE light_app_services
  ADD COLUMN IF NOT EXISTS max_response_bytes INTEGER NOT NULL DEFAULT 5242880;
ALTER TABLE light_app_services
  ADD COLUMN IF NOT EXISTS idempotency_required INTEGER NOT NULL DEFAULT 1;
ALTER TABLE light_app_services
  ADD COLUMN IF NOT EXISTS confirmation_json TEXT NOT NULL DEFAULT '{}';
ALTER TABLE light_app_services
  ADD COLUMN IF NOT EXISTS allow_private_network INTEGER NOT NULL DEFAULT 0;

CREATE TABLE IF NOT EXISTS light_app_service_operations (
  id                        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  op_id                     TEXT NOT NULL UNIQUE,
  service_id                TEXT NOT NULL
    REFERENCES light_app_services(service_id) ON DELETE CASCADE,
  app_id                    TEXT NOT NULL
    REFERENCES light_apps(app_id) ON DELETE CASCADE,
  tool                      TEXT NOT NULL,
  args_hash                 TEXT NOT NULL,
  idempotency_key           TEXT NOT NULL,
  status                    TEXT NOT NULL,
  confirmation_token_hash   TEXT NOT NULL DEFAULT '',
  confirmation_expires_at   INTEGER,
  result_json               TEXT NOT NULL DEFAULT '',
  error_code                TEXT NOT NULL DEFAULT '',
  error_message             TEXT NOT NULL DEFAULT '',
  actor_user_id             INTEGER NOT NULL
    REFERENCES users(id) ON DELETE CASCADE,
  created_at                INTEGER NOT NULL,
  updated_at                INTEGER NOT NULL,
  expires_at                INTEGER
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_light_app_service_operations_idem
  ON light_app_service_operations(service_id, tool, actor_user_id, idempotency_key)
  WHERE idempotency_key <> '';
CREATE INDEX IF NOT EXISTS idx_light_app_service_operations_app
  ON light_app_service_operations(app_id, created_at);
CREATE INDEX IF NOT EXISTS idx_light_app_service_operations_status
  ON light_app_service_operations(status, created_at);

UPDATE _schema_version SET version = 52;
